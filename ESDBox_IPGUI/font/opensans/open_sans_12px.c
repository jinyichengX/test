const  ipgui_glyph_t* open_sans_12px_get_glyph(unsigned char char_code)
{
    if (char_code < 128) {
        return &open_sans_12px_glyph_array[char_code];
    }
    return &open_sans_12px_char_063;  /* 返回'?'字符 */
}

/* 文本宽度计算 */
unsigned short open_sans_12px_text_width(const char* text)
{
    unsigned short width = 0;
    while (*text) {
        unsigned char ch = (unsigned char)*text;
        if (ch < 128) {
            const  ipgui_glyph_t* glyph = &open_sans_12px_glyph_array[ch];
            width += glyph->advance;
        }
        text++;
    }
    return width;
}
